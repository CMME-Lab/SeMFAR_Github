"""k-Wave simulator whose LR acoustic maps are derived from HR maps.

The existing simulator is intentionally left unchanged.  HR is generated by
the original implementation.  For every lower-resolution variant, sound speed
and density are area-downsampled from the saved HR phantom without any
renormalisation or newly generated random field.
"""

import json
import os
import time
from typing import Dict, List

import cv2
import numpy as np
import scipy.io

from core.simulate_kwave import (
    UltrasoundSimulator,
)


def _resize_xy(volume: np.ndarray, target_shape, interpolation: int) -> np.ndarray:
    """Resize only physical x/y axes, retaining the elevation axis."""
    target_x, target_y, target_z = target_shape
    if volume.ndim != 3 or volume.shape[2] != target_z:
        raise ValueError(
            f"Expected 3-D volume with Nz={target_z}, got {volume.shape}"
        )
    resized = np.empty((target_x, target_y, target_z), dtype=np.float64)
    for z_idx in range(target_z):
        resized[:, :, z_idx] = cv2.resize(
            np.asarray(volume[:, :, z_idx], dtype=np.float64),
            (target_y, target_x),
            interpolation=interpolation,
        )
    return resized


class HRDerivedLRUltrasoundSimulator(UltrasoundSimulator):
    """Use original generation for HR and HR-derived property maps for LR."""

    def run_simulation(
        self,
        sample_name: str,
        input_data_path: str,
        output_path: str,
        noise_levels: List[str] = ["low"],
        run_simulation: bool = True,
    ) -> Dict:
        is_hr = (
            abs(float(self.config.sc_w_x) - 1.0) < 1e-12
            and abs(float(self.config.sc_w_y) - 1.0) < 1e-12
        )
        if is_hr:
            print("PAIRING MODE: generating canonical HR acoustic maps")
            return super().run_simulation(
                sample_name,
                input_data_path,
                output_path,
                noise_levels,
                run_simulation,
            )

        results_folder = os.path.join(output_path, sample_name)
        os.makedirs(results_folder, exist_ok=True)
        target_shape = (
            int(self.config.Nx),
            int(self.config.Ny + self.config.number_scan_lines * self.config.element_width),
            int(self.config.Nz),
        )
        results = {}

        # output_path is .../<simulation root>/<variant>; HR is its sibling.
        simulation_root = os.path.dirname(os.path.normpath(output_path))
        hr_sample_folder = os.path.join(simulation_root, "sc1.0", sample_name)

        for noise_level in noise_levels:
            hr_phantom_file = os.path.join(
                hr_sample_folder, f"phantom_{noise_level}.mat"
            )
            if not os.path.exists(hr_phantom_file):
                raise FileNotFoundError(
                    "Canonical HR phantom must be generated first: "
                    f"{hr_phantom_file}"
                )

            print(f"PAIRING MODE: loading HR maps from {hr_phantom_file}")
            hr = scipy.io.loadmat(hr_phantom_file)
            hr_sos = np.asarray(hr["sound_speed_map"], dtype=np.float64)
            hr_density = np.asarray(hr["density_map"], dtype=np.float64)

            # INTER_AREA performs anti-aliased area averaging.  Deliberately do
            # not subtract a mean, divide by a standard deviation, regenerate
            # noise, or otherwise alter the downsampled acoustic properties.
            sound_speed_map = _resize_xy(hr_sos, target_shape, cv2.INTER_AREA)
            density_map = _resize_xy(hr_density, target_shape, cv2.INTER_AREA)
            semantic_map = _resize_xy(
                np.asarray(hr["semantic_map"]), target_shape, cv2.INTER_NEAREST
            ).astype(np.int16)
            grf = _resize_xy(
                np.asarray(hr["grf"]), target_shape, cv2.INTER_AREA
            )
            tumor_mask_3d = _resize_xy(
                np.asarray(hr["tumor_mask_3d"], dtype=np.float64),
                target_shape,
                cv2.INTER_NEAREST,
            ) >= 0.5

            run_seed = int(np.asarray(hr["run_seed"]).squeeze())
            sample_seed = int(np.asarray(hr["sample_seed"]).squeeze())
            level_seed = int(np.asarray(hr["noise_level_seed"]).squeeze())

            print(
                "PAIRING MODE: HR -> LR INTER_AREA, no re-standardisation\n"
                f"  HR shape: {hr_sos.shape}\n"
                f"  LR shape: {sound_speed_map.shape}\n"
                f"  HR SoS std: {hr_sos.std():.6f}; LR SoS std: {sound_speed_map.std():.6f}\n"
                f"  HR density std: {hr_density.std():.6f}; LR density std: {density_map.std():.6f}"
            )

            phantom_file = os.path.join(results_folder, f"phantom_{noise_level}.mat")
            scipy.io.savemat(
                phantom_file,
                {
                    "sound_speed_map": sound_speed_map,
                    "density_map": density_map,
                    "semantic_map": semantic_map,
                    "grf": grf,
                    "tumor_mask_3d": tumor_mask_3d,
                    "sample_name": sample_name,
                    "run_seed": run_seed,
                    "sample_seed": sample_seed,
                    "noise_level_seed": level_seed,
                    "derived_from_hr": np.uint8(1),
                    "downsampling_method": "cv2.INTER_AREA",
                    "restandardized_after_downsampling": np.uint8(0),
                    "source_hr_phantom": hr_phantom_file,
                },
            )

            validation = {
                "sample_name": sample_name,
                "source_hr_phantom": hr_phantom_file,
                "hr_shape": list(hr_sos.shape),
                "lr_shape": list(sound_speed_map.shape),
                "downsampling_method": "cv2.INTER_AREA",
                "restandardized_after_downsampling": False,
                "run_seed": run_seed,
                "sample_seed": sample_seed,
                "noise_level_seed": level_seed,
                "hr_sound_speed_std": float(hr_sos.std()),
                "lr_sound_speed_std": float(sound_speed_map.std()),
                "hr_density_std": float(hr_density.std()),
                "lr_density_std": float(density_map.std()),
            }
            with open(
                os.path.join(results_folder, f"pairing_validation_{noise_level}.json"),
                "w",
                encoding="utf-8",
            ) as validation_file:
                json.dump(validation, validation_file, indent=2)

            self._visualize_phantom(
                sound_speed_map, semantic_map, sample_name, noise_level, results_folder
            )

            if run_simulation:
                print("Running LR k-Wave with HR-derived acoustic maps...")
                simulation_start = time.perf_counter()
                scan_lines = self._run_kwave_simulation(
                    sound_speed_map=sound_speed_map,
                    density_map=density_map,
                )
                runtime_minutes = (time.perf_counter() - simulation_start) / 60.0
                simulation_file = os.path.join(
                    results_folder, f"simulation_{noise_level}.mat"
                )
                scipy.io.savemat(
                    simulation_file,
                    {
                        "scan_lines": scan_lines,
                        "sound_speed_map": sound_speed_map,
                        "density_map": density_map,
                        "kgrid_dt": self.kgrid.dt,
                        "kgrid_Nt": self.kgrid.Nt,
                        "element_width": self.config.element_width,
                        "sample_name": sample_name,
                        "run_seed": run_seed,
                        "sample_seed": sample_seed,
                        "noise_level_seed": level_seed,
                        "sc_w_x": float(self.config.sc_w_x),
                        "sc_w_y": float(self.config.sc_w_y),
                        "derived_from_hr": np.uint8(1),
                        "downsampling_method": "cv2.INTER_AREA",
                        "restandardized_after_downsampling": np.uint8(0),
                        "source_hr_phantom": hr_phantom_file,
                        "simulation_time_minutes": float(runtime_minutes),
                        "pml_x_size": int(self.config.pml_x_size),
                        "pml_y_size": int(self.config.pml_y_size),
                        "tone_burst_freq": float(self.config.tone_burst_freq),
                        "tone_burst_cycles": float(self.config.tone_burst_cycles),
                    },
                )
                results[noise_level] = {
                    "scan_lines": scan_lines,
                    "phantom_file": phantom_file,
                    "simulation_file": simulation_file,
                }
            else:
                results[noise_level] = {"phantom_file": phantom_file}

        return results
